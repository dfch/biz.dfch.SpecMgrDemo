#!/usr/bin/env bash
# feat-6-contracts-openapi-pipeline, Task 120.120 (REQ-001, REQ-004, REQ-009, REQ-011, ACC-002, ACC-009, ACC-013)
#
# Makes all generated code again from contracts/openapi.yaml:
#   - the Spring server interfaces (Java) in backend/src/generated, with openapi-generator-maven-plugin, generator `spring`;
#   - the Zod schemas and the TypeScript types in frontend/src/generated, with Kubb (the runner frontend/generate.mjs).
# Both folders are committed to git. The gate for generated code (check-generated.sh, task 130.100) makes the code again and compares it with git.
#
# Usage: generate.sh <backend dir> <frontend dir>
#   <backend dir>   the Maven module with mvnw, for example backend
#   <frontend dir>  the pnpm module, for example frontend
#
# What the script does:
#   1. verify_generator_plugin (_lib.sh): the sha256 of the jar of the generator plugin must be the value of
#      OPENAPI_GENERATOR_MAVEN_PLUGIN_SHA256 (the dependencies of the plugin are not checked, GitHub issue #23).
#   2. It deletes <backend dir>/src/generated, so a file that is no longer generated is gone. It starts the execution
#      `spring-interfaces` of the plugin through ./mvnw (never the Maven of the PATH). The options are in backend/pom.xml.
#   3. It writes the mark "generated, do not change" to <backend dir>/src/generated/README.md, and stops if a Java file has no
#      @Generated annotation (this is the mark in each file; the generator writes it).
#   4. install_frontend (_lib.sh): pnpm install --frozen-lockfile --ignore-scripts, and the versions of the packages.
#   5. It starts the runner of Kubb (the programmatic interface, so Kubb makes no network call). Kubb deletes
#      <frontend dir>/src/generated before it writes. The script sets KUBB_DISABLE_TELEMETRY=1 and DO_NOT_TRACK=1, so Kubb
#      sends no usage data (the workflow gate does not allow `env:` in a workflow, so the script sets them; the owner accepted this).
#   6. It writes the mark to <frontend dir>/src/generated/README.md, and stops if a file does not have the banner of Kubb
#      ("Generated by Kubb ... Do not edit manually.").
#
# The result is the same on each run (REQ-011): the generator has hideGenerationTimestamp=true, the files have no time, no
# version value that changes, and no path of the machine (just test-generate-gate checks this, ACC-013). The marks are in this
# script and not in a file of tools/, so the script is the one place for their text.
#
# The ORDER of the import lines in the generated Java files comes from a hash set iteration in the JDK (the pinned JDK of
# tools/versions.env, see the generated files: the imports are not alphabetical). A change of the JDK can reorder the
# imports, and then the new files are not the same as the committed files, so `just check-generated` stops. In this case,
# run `just generate` with the new JDK and commit the result (and the owner changes the pin of the JDK).
#
# Needs JDK 21 (JAVA_HOME or the PATH; the wrapper downloads Maven), Node, pnpm and the network for the first run (Maven Central
# and the npm registry). The script changes only the two generated folders and, as the install, the folders
# <frontend dir>/node_modules and ~/.m2 (the first is in .gitignore).

set -euo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/_lib.sh"

[[ $# -eq 2 ]] || die "Usage: generate.sh <backend dir> <frontend dir>"
backend="$1"
frontend="$2"
[[ -d "${backend}" ]] || die "The Maven module does not exist: ${backend}"
[[ -d "${frontend}" ]] || die "The pnpm module does not exist: ${frontend}"
backend="$(cd "${backend}" && pwd)"
frontend="$(cd "${frontend}" && pwd)"
[[ -f "${backend}/pom.xml" ]] || die "${backend}/pom.xml does not exist."
[[ -f "${frontend}/generate.mjs" && -f "${frontend}/kubb.config.mjs" ]] \
    || die "${frontend}/generate.mjs or ${frontend}/kubb.config.mjs does not exist (the runner of Kubb)."
plugin_version="$(version_of OPENAPI_GENERATOR_MAVEN_PLUGIN_VERSION)"
repo_local="${GENERATOR_MAVEN_REPO_LOCAL:-${HOME}/.m2/repository}"

# --- Java: the Spring server interfaces ----------------------------------------------------------------------------------
verify_generator_plugin "${backend}"
java_dir="${backend}/src/generated"
log "Delete ${java_dir}"
rm -rf "${java_dir}"
log "Generate the Spring server interfaces (execution spring-interfaces)"
(
    cd "${backend}" && ./mvnw --batch-mode --no-transfer-progress --file pom.xml "-Dmaven.repo.local=${repo_local}" \
        "org.openapitools:openapi-generator-maven-plugin:${plugin_version}:generate@spring-interfaces"
) || die "Maven did not generate the Java code (see above)."

java_files="$(find "${java_dir}" -type f -name '*.java' | LC_ALL=C sort)"
[[ -n "${java_files}" ]] || die "The generator made no Java file in ${java_dir}."
while IFS= read -r file; do
    grep -q '^@Generated(' "${file}" || die "${file} has no @Generated annotation. The generator writes it, and it is the mark of the file."
done <<<"${java_files}"

cat >"${java_dir}/README.md" <<'README'
# Generated code, do not change

Do not change a file in this folder by hand. `just generate` makes all files in this folder (and deletes the old ones) from
`contracts/openapi.yaml`, with the generator `spring` of `openapi-generator-maven-plugin`. A change by hand is lost at the next
generation, and the gate for generated code stops a pull request that has it.

To change an interface, change `contracts/openapi.yaml` first, and then run `just generate`. See `contracts/README.md`.

Each Java file has the annotation `@Generated`. The folder `.openapi-generator` has the hash of the OpenAPI file that the
generator read.
README
log "Wrote ${java_dir}/README.md ($(wc -l <<<"${java_files}") Java files)"

# --- TypeScript: the Zod schemas -----------------------------------------------------------------------------------------
install_frontend "${frontend}"
ts_dir="${frontend}/src/generated"
log "Generate the Zod schemas with Kubb (the programmatic runner, no network call, no telemetry)"
(
    cd "${frontend}"
    export KUBB_DISABLE_TELEMETRY=1 DO_NOT_TRACK=1
    node generate.mjs
) || die "Kubb did not generate the code (see above)."

ts_files="$(find "${ts_dir}" -type f -name '*.ts' | LC_ALL=C sort)"
[[ -n "${ts_files}" ]] || die "Kubb made no TypeScript file in ${ts_dir}."
while IFS= read -r file; do
    if ! grep -q '^\* Generated by Kubb (https://kubb.dev/)\.$' "${file}" || ! grep -q '^\* Do not edit manually\.$' "${file}"; then
        die "${file} has no banner of Kubb (\"Generated by Kubb ... Do not edit manually.\"). It is the mark of the file."
    fi
done <<<"${ts_files}"

cat >"${ts_dir}/README.md" <<'README'
# Generated code, do not change

Do not change a file in this folder by hand. `just generate` makes all files in this folder (and deletes the old ones) from
`contracts/openapi.yaml`, with Kubb (the runner `generate.mjs` of the folder `frontend`). A change by hand is lost at the next
generation, and the gate for generated code stops a pull request that has it.

To change an interface, change `contracts/openapi.yaml` first, and then run `just generate`. See `contracts/README.md`.

Each TypeScript file starts with the banner "Generated by Kubb. Do not edit manually."
The folder `zod` has the Zod schemas (for example `errorCodeSchema`, the list of error codes), and the folder `types` has
the TypeScript types.
README
log "Wrote ${ts_dir}/README.md ($(wc -l <<<"${ts_files}") TypeScript files)"
log "PASS"
