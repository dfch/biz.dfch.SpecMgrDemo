// The Kubb configuration (feat-6-contracts-openapi-pipeline, Task 120.110, REQ-004, REQ-006, REQ-011).
//
// Kubb makes the Zod schemas and the TypeScript types in src/generated from contracts/openapi.yaml. The runner
// generate.mjs starts it (and not the command `kubb generate`, see README.md). Do not add an option that writes a
// time, a version or a path of this machine to a file: two runs must make the same files (REQ-011).
//
// The paths are relative to the folder of this file (`root`), so the result does not depend on the working
// folder of the caller.
import { fileURLToPath } from 'node:url'
import { defineConfig } from 'kubb/config'
import { pluginTs } from '@kubb/plugin-ts'
import { pluginZod } from '@kubb/plugin-zod'

export default defineConfig({
  root: fileURLToPath(new URL('.', import.meta.url)),
  input: '../contracts/openapi.yaml',
  // clean: Kubb deletes the folder before it writes, so a file that the OpenAPI file no longer needs is gone.
  // Every file in the folder has the banner of Kubb: "Generated by Kubb (https://kubb.dev/). Do not edit manually."
  // `barrel: false` of each plugin: Kubb makes no `index.ts` that re-exports the files, because a barrel file has no
  // banner. A user imports a schema from its own file (for example `zod/errorCodeSchema.ts`).
  output: { path: './src/generated', clean: true },
  plugins: [
    // The TypeScript types (src/generated/types).
    pluginTs({ output: { path: 'types', barrel: false } }),
    // The Zod schemas (src/generated/zod). The schema of the list of error codes is `errorCodeSchema`: Kubb makes
    // one schema for each component of the OpenAPI file, and `Problem.code` uses it (ACC-008).
    pluginZod({ output: { path: 'zod', barrel: false }, inferred: true }),
  ],
})
